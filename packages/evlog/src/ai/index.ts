export interface AILogger {
  /**
   * Wrap a language model with evlog middleware.
   * All `generateText` and `streamText` calls using the wrapped model
   * are captured automatically into the wide event.
   *
   * Accepts a language model object (`LanguageModelV3` or `LanguageModelV4`)
   * or a model string (e.g. `'anthropic/claude-sonnet-4.6'`).
   * Strings are resolved via the AI SDK gateway.
   *
   * On AI SDK v7, the wrapped model is a `LanguageModelV4`. On v6 it remains
   * a `LanguageModelV3`. Both are accepted as input.
   *
   * Also works with pre-wrapped models (e.g. from supermemory, guardrails):
   * `ai.wrap(withSupermemory(base, orgId))` composes correctly.
   *
   * @example Gateway model string
   * ```ts
   * const ai = createAILogger(log)
   * const model = ai.wrap('anthropic/claude-sonnet-4.6')
   * ```
   *
   * @example Provider model object (V3 or V4)
   * ```ts
   * const ai = createAILogger(log)
   * const model = ai.wrap(anthropic('claude-sonnet-4.6'))
   * ```
   */
  wrap: (model: LanguageModel) => LanguageModel

  /**
   * Manually capture token usage from an `embed()` or `embedMany()` result.
   * Embedding models use a different type than language models, so they
   * cannot be wrapped with middleware.
   *
   * @example
   * ```ts
   * const { embedding, usage } = await embed({ model: embeddingModel, value: query })
   * ai.captureEmbed({ usage })
   *
   * // With model info (v2)
   * ai.captureEmbed({ usage, model: 'text-embedding-3-small', dimensions: 1536 })
   *
   * // After embedMany
   * ai.captureEmbed({ usage, count: texts.length })
   * ```
   */
  captureEmbed: (result: {
    usage: { tokens: number }
    model?: string
    dimensions?: number
    count?: number
  }) => void

  /**
   * Get a snapshot of the current AI execution metadata.
   *
   * Returns the same structured object that is written to the `ai` field
   * of the wide event. Safe to call at any time — including inside the
   * AI SDK's `onFinish` callback, after `await generateText()`, or while a
   * stream is in progress.
   *
   * The returned snapshot is a fresh copy: mutating it does not affect
   * subsequent calls or the underlying state.
   *
   * @example Persist execution history after a run
   * ```ts
   * const ai = createAILogger(log, { cost: { ... } })
   *
   * await generateText({ model: ai.wrap('anthropic/claude-sonnet-4.6'), prompt })
   *
   * const metadata = ai.getMetadata()
   * await db.insert('ai_runs', metadata)
   * ```
   *
   * @example Surface usage to end-users in a streaming response
   * ```ts
   * const result = streamText({
   *   model: ai.wrap('anthropic/claude-sonnet-4.6'),
   *   messages,
   *   onFinish: () => {
   *     const { totalTokens, estimatedCost } = ai.getMetadata()
   *     trackUsage(userId, { totalTokens, estimatedCost })
   *   },
   * })
   * ```
   */
  getMetadata: () => AIMetadata

  /**
   * Get the current estimated cost in dollars.
   *
   * Returns `undefined` if no `cost` map was provided to `createAILogger`,
   * or if the model is not in the pricing map.
   *
   * Convenience for `getMetadata().estimatedCost`.
   *
   * @example
   * ```ts
   * const ai = createAILogger(log, {
   *   cost: { 'claude-sonnet-4.6': { input: 3, output: 15 } },
   * })
   *
   * await generateText({ model: ai.wrap('anthropic/claude-sonnet-4.6'), prompt })
   *
   * console.log(`Cost: $${ai.getEstimatedCost()?.toFixed(4)}`)
   * ```
   */
  getEstimatedCost: () => number | undefined

  /**
   * Subscribe to metadata updates.
   *
   * The callback fires every time the underlying state flushes — once per
   * step (in multi-step agent runs), once per `captureEmbed` call, on
   * model errors, and once on `createEvlogIntegration`'s `onFinish`.
   *
   * Each invocation receives a fresh snapshot (same shape as `getMetadata`).
   * Returns an unsubscribe function.
   *
   * @example Stream incremental usage updates to the client
   * ```ts
   * const ai = createAILogger(log)
   *
   * ai.onUpdate((metadata) => {
   *   pushToClient({ type: 'ai-progress', metadata })
   * })
   *
   * const result = streamText({ model: ai.wrap('...'), messages })
   * ```
   *
   * @example Cleanup
   * ```ts
   * const off = ai.onUpdate((metadata) => { ... })
   * // later
   * off()
   * ```
   */
  onUpdate: (callback: AIMetadataListener) => () => void

  /**
   * Internal accumulator state exposed for `createEvlogIntegration` to share.
   * @internal
   */
  _state: AccumulatorState
}

interface UsageAccumulator {
  inputTokens: number
  outputTokens: number
  cacheReadTokens: number
  cacheWriteTokens: number
  reasoningTokens: number
}

function addUsage(
  acc: UsageAccumulator,
  usage: {
    inputTokens: { total: number | undefined, cacheRead?: number | undefined, cacheWrite?: number | undefined }
    outputTokens: { total: number | undefined, reasoning?: number | undefined }
  },
): void {
  acc.inputTokens += usage.inputTokens.total ?? 0
  acc.outputTokens += usage.outputTokens.total ?? 0
  acc.cacheReadTokens += usage.inputTokens.cacheRead ?? 0
  acc.cacheWriteTokens += usage.inputTokens.cacheWrite ?? 0
  acc.reasoningTokens += usage.outputTokens.reasoning ?? 0
}

/**
 * When using `gateway('google/gemini-3-flash')`, the model object has
 * `provider: 'gateway'` and `modelId: 'google/gemini-3-flash'`.
 * This extracts the real provider and model name from the modelId.
 */
function resolveProviderAndModel(provider: string, modelId: string): { provider: string, model: string } {
  if (provider !== 'gateway' || !modelId.includes('/')) {
    return { provider, model: modelId }
  }
  const slashIndex = modelId.indexOf('/')
  return {
    provider: modelId.slice(0, slashIndex),
    model: modelId.slice(slashIndex + 1),
  }
}

